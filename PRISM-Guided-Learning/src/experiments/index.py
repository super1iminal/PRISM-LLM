"""The experiments index, out/results/experiments/README.md: for every experiment file (configs/experiments/*.yaml),
per cell and benchmark, the runs found against the repeats wanted, pending runs and the repeats `--run` would launch;
for comparisons, whether each baseline is certified on every target; a link to each report. It also draws the RQ2
overview (rq2_overview.png): every ablation cell on every benchmark, against the core configuration.
"""
from pathlib import Path
from typing import List, Optional

import numpy as np
import pandas as pd
import yaml

from experiments.ablation import Ablation
from experiments.base import EXPERIMENTS_DIR, REPORTS_PATH, Experiment, experiment, held_out
from experiments.comparison import Comparison, _pyplot, short_label
from experiments.store import RunStore, fingerprint
from transfer import parse_ids


def experiment_files() -> List[Path]:
    """Every experiment file (a yaml with a `kind`), comparisons first."""
    paths = [p for p in sorted(EXPERIMENTS_DIR.glob("*.yaml"))
             if (yaml.safe_load(p.read_text(encoding="utf-8")) or {}).get("kind")]
    return sorted(paths, key=lambda p: (not p.stem.startswith("rq1"), p.stem))


def _status(exp: Experiment, cell, bench: str) -> str:
    units = [u for u in exp.units if u.cell.name == cell.name and u.bench.name == bench]
    if not units:
        return ""
    u = units[0]
    text = f"{len(u.runs)}/{cell.repeats}"
    if u.pending:
        text += f", {len(u.pending)} pending"
    if u.missing:
        text += f", **{u.missing} missing**"
    elif not cell.launch and len(u.runs) < cell.repeats:
        text += " (launch: false)"
    return text if len(u.runs) < cell.repeats or u.pending else f"{text} ✓"


def _baseline_status(exp: Comparison, base: dict, bench: str) -> str:
    if bench not in base["config"]:
        return ""
    targets = set(parse_ids(exp.spec["benchmarks"][bench].targets))
    rules = ("final", "open") if base.get("ties", True) else ("final",)
    done = [r for r in rules if exp._csv(base["config"][bench], r).exists()
            and targets <= set(pd.read_csv(exp._csv(base["config"][bench], r)).target)]
    if len(done) == len(rules):
        return "certified ✓"
    return "**unchecked**" if "final" not in done else "certified, **ties open unchecked**"


def index_page(exps: List[Experiment], overview: Optional[Path]) -> str:
    lines = ["# Experiments index", "",
             "Generated by `python src/run_experiment.py --index` from `configs/experiments/*.yaml` and the run store "
             "(`docs/experiments.md`). Per cell and benchmark: runs found / repeats wanted (✓: complete), runs started "
             "but unfinished (pending), and the repeats `--run` would launch (missing). Cells with `launch: false` "
             "(Sonnet) need Asher's go-ahead. Validation targets only; the test set is sealed.", ""]
    missing = {}                                 # configuration -> repeats to launch (a shared one counts once)
    for exp in exps:
        for u in exp.units:
            if u.missing:
                key = fingerprint(u.cfg)
                missing[key] = max(missing.get(key, 0), u.missing)
    lines += [f"**Missing:** {sum(missing.values())} repeats of {len(missing)} configurations (a configuration "
              "several cells share counts once)." if missing else "**Missing:** none.", ""]
    if overview:
        lines += [f"RQ2 at a glance: [{overview.name}]({overview.name}) (every ablation cell against the core "
                  "configuration, held-out targets certified per rule list).", ""]
    for exp in exps:
        benches = list(exp.spec["benchmarks"])
        report = f"{exp.name}/REPORT.md"
        lines += [f"## [{exp.title}]({report})", "", f"`configs/experiments/{exp.name}.yaml`", "",
                  "| cell | " + " | ".join(benches) + " |", "|---|" + "---|" * len(benches)]
        for cell in exp.spec["cells"]:
            lines.append(f"| {cell.name} | " + " | ".join(_status(exp, cell, b) for b in benches) + " |")
        if isinstance(exp, Comparison):
            for base in exp.baselines():
                lines.append(f"| {base['name']} (baseline) | "
                             + " | ".join(_baseline_status(exp, base, b) for b in benches) + " |")
        lines.append("")
    return "\n".join(lines)


def overview_figure(exps: List[Ablation], path: Path) -> Optional[Path]:
    """One panel per benchmark: every ablation cell (grouped by experiment) as its runs (hollow dots) and their mean,
    the core configuration's mean as a dashed line. Cells without runs say so."""
    frames = [(exp, exp.collect()) for exp in exps]
    frames = [(exp, runs) for exp, runs in frames if not runs.empty]
    if not frames:
        return None
    benches = {}
    for exp, _ in frames:
        for name, bench in exp.spec["benchmarks"].items():
            benches.setdefault(name, bench)
    rows = [("Core configuration (every reference)", None, None)]
    for exp, _ in frames:
        rows.append((exp.title, exp, None))
        rows += [(cell.name, exp, cell) for cell in exp.spec["cells"] if cell.name != exp.reference()]
    plt = _pyplot()
    from theme import GRID, INK, INK_2, OURS, SURFACE, style

    fig, axes = plt.subplots(1, len(benches), figsize=(3.4 * len(benches) + 3.6, 0.24 * len(rows) + 1.4),
                             sharey=True, squeeze=False, facecolor=SURFACE)
    for ax, bench in zip(axes[0], benches.values()):
        style(ax, short_label(bench))
        ax.grid(axis="y", visible=False)
        ax.grid(axis="x", color=GRID, linewidth=0.8)
        first_exp, first_runs = frames[0]
        reference = first_runs[(first_runs.bench == bench.name) & (first_runs.cell == first_exp.reference())]
        ref = reference.certified.dropna()
        if not ref.empty:
            ax.axvline(ref.mean(), color=INK_2, linestyle="--", linewidth=1)
        for y, (label, exp, cell) in enumerate(rows):
            if exp is None:
                values = ref
            elif cell is None or bench.name not in cell.only:
                continue
            else:
                runs = dict(frames)[exp]
                values = runs[(runs.bench == bench.name) & (runs.cell == cell.name)].certified.dropna()
            if values.empty:
                ax.text(0.02, y, "no runs", fontsize=6.5, color=INK_2, va="center",
                        transform=ax.get_yaxis_transform())
                continue
            ax.plot([values.min(), values.max()], [y, y], color=GRID, linewidth=4, solid_capstyle="round")
            ax.scatter(values, [y] * len(values), s=12, facecolors="none", edgecolors=INK_2, linewidths=0.9, zorder=3)
            ax.scatter([values.mean()], [y], s=34, color=OURS if exp is None else INK, zorder=4)
        groups = bench.groups
        of = max((len(parse_ids(t)) for t in groups.values()), default=len(held_out(bench)))
        ax.set_xlim(-0.3, of + 0.3)
        ax.set_xticks(range(0, of + 1, 1 if of <= 10 else 5))
        ax.set_xlabel(f"certified per rule list (of {of}{' in its family' if groups else ''})", color=INK_2, fontsize=8)
        ax.set_ylim(len(rows) - 0.5, -0.5)
    ax0 = axes[0][0]
    ax0.set_yticks(range(len(rows)))
    ax0.set_yticklabels([label for label, *_ in rows], fontsize=7.5, color=INK)
    for tick, (_, exp, cell) in zip(ax0.get_yticklabels(), rows):
        if exp is not None and cell is None:
            tick.set_fontweight("bold")
    fig.suptitle("RQ2: every ablation against the core configuration (validation; dots: runs, filled: mean)",
                 x=0.01, ha="left", fontsize=10.5, fontweight="bold", color=INK)
    fig.tight_layout()
    fig.savefig(path, dpi=180, facecolor=SURFACE)
    plt.close(fig)
    return path


def write_index(store: Optional[RunStore] = None) -> Path:
    """The index page and the RQ2 overview figure, from every experiment file."""
    store = store or RunStore()
    exps = [experiment(p, store) for p in experiment_files()]
    REPORTS_PATH.mkdir(parents=True, exist_ok=True)
    overview = overview_figure([e for e in exps if isinstance(e, Ablation)], REPORTS_PATH / "rq2_overview.png")
    path = REPORTS_PATH / "README.md"
    path.write_text(index_page(exps, overview), encoding="utf-8")
    return path
